package it.gruppoinit.domain.helper;

public class LeggiAttoHelper {

    private String idDocumento;
    private String organo;
    private String anno;
    private String numero;
    private String utente;
    private String codiceAmm;
    private String codiceAOO;
    private String tipo;
    private String ruolo;

    public String getIdDocumento() {

	return idDocumento;
    }

    public void setIdDocumento(String idDocumento) {

	this.idDocumento = idDocumento;
    }

    public String getOrgano() {

	return organo;
    }

    public void setOrgano(String organo) {

	this.organo = organo;
    }

    public String getAnno() {

	return anno;
    }

    public void setAnno(String anno) {

	this.anno = anno;
    }

    public String getNumero() {

	return numero;
    }

    public void setNumero(String numero) {

	this.numero = numero;
    }

    public String getUtente() {

	return utente;
    }

    public void setUtente(String utente) {

	this.utente = utente;
    }

    public String getCodiceAmm() {

	return codiceAmm;
    }

    public void setCodiceAmm(String codiceAmm) {

	this.codiceAmm = codiceAmm;
    }

    public String getCodiceAOO() {

	return codiceAOO;
    }

    public void setCodiceAOO(String codiceAOO) {

	this.codiceAOO = codiceAOO;
    }

    public String getTipo() {

	return tipo;
    }

    public void setTipo(String tipo) {

	this.tipo = tipo;
    }

    public String getRuolo() {

	return ruolo;
    }

    public void setRuolo(String ruolo) {

	this.ruolo = ruolo;
    }
}
