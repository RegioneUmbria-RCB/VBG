package it.gruppoinit.stc.dao.impl;

public class PraticheHelper {

    private Integer id;
    private String idPratica;
    private String idEnte;
    private Integer idNodo;
    private String idSportello;

    public Integer getId() {

	return id;
    }

    public void setId(Integer id) {

	this.id = id;
    }

    public String getIdPratica() {

	return idPratica;
    }

    public void setIdPratica(String idPratica) {

	this.idPratica = idPratica;
    }

    public String getIdEnte() {

	return idEnte;
    }

    public void setIdEnte(String idEnte) {

	this.idEnte = idEnte;
    }

    public Integer getIdNodo() {

	return idNodo;
    }

    public void setIdNodo(Integer idNodo) {

	this.idNodo = idNodo;
    }

    public String getIdSportello() {

	return idSportello;
    }

    public void setIdSportello(String idSportello) {

	this.idSportello = idSportello;
    }
}
