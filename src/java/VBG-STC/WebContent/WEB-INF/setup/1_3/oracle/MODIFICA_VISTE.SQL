CREATE OR REPLACE VIEW VW_MESSAGGIPRATICHE AS
SELECT
    MESSAGGIPRATICHE.ID,
    RICHIESTE.FKIDNODO MITT_IDNODO, 
    RICHIESTE.IDENTE MITT_IDENTE ,
    RICHIESTE.IDSPORTELLO MITT_IDSPORTELLO,
    RICHIESTE.IDPRATICA MITT_IDPRATICA,
    RICHIESTE.NUMPRATICA MITT_NUMPRATICA,
    RICHIESTE.DATAPRATICA MITT_DATAPRATICA,
    RISPOSTE.FKIDNODO DEST_IDNODO, 
    RISPOSTE.IDENTE DEST_IDENTE ,
    RISPOSTE.IDSPORTELLO DEST_IDSPORTELLO,
    RISPOSTE.IDPRATICA DEST_IDPRATICA,
    RISPOSTE.NUMPRATICA DEST_NUMPRATICA,
    RISPOSTE.DATAPRATICA DEST_DATAPRATICA
  FROM MESSAGGIPRATICHE
  INNER JOIN PRATICHE RICHIESTE
  ON RICHIESTE.ID= MESSAGGIPRATICHE.FKIDRICHIESTA
  INNER JOIN PRATICHE RISPOSTE
  ON RISPOSTE.ID= MESSAGGIPRATICHE.FKIDRISPOSTA
  ORDER BY MESSAGGIPRATICHE.ID;
  
 CREATE OR REPLACE VIEW VW_MESSAGGIATTIVITA AS
SELECT 
    MESSAGGIATTIVITA.ID,
    RICHIESTE.FKIDNODO MITT_IDNODO,
    RICHIESTE.IDENTE MITT_IDENTE ,
    RICHIESTE.IDSPORTELLO MITT_IDSPORTELLO,
    RICHIESTE.IDPRATICA MITT_IDPRATICA ,
    RICHIESTE.NUMPRATICA MITT_NUMPRATICA ,
    ATT_RICHIESTE.IDATTIVITA MITT_ATT_ID ,
    ATT_RICHIESTE.TIPOATTIVITA MITT_ATT_TIPO ,
    ATT_RICHIESTE.IDPROCEDIMENTO MITT_ATT_IDPROC ,
    ATT_RICHIESTE.DATAATTIVITA MITT_ATT_DATA,
    RISPOSTE.FKIDNODO DEST_IDNODO,
    RISPOSTE.IDENTE DEST_IDENTE,
    RISPOSTE.IDSPORTELLO DEST_IDSPORTELLO ,
    RISPOSTE.IDPRATICA DEST_IDPRATICA ,
    RISPOSTE.NUMPRATICA DEST_NUMPRATICA,
    ATT_RISPOSTE.IDATTIVITA DEST_ATT_ID ,
    ATT_RISPOSTE.TIPOATTIVITA DEST_ATT_TIPO ,
   ATT_RISPOSTE.IDPROCEDIMENTO DEST_ATT_IDPROC,
    ATT_RISPOSTE.DATAATTIVITA DEST_ATT_DATA
  FROM 
  MESSAGGIATTIVITA
  INNER JOIN ATTIVITA ATT_RICHIESTE ON ATT_RICHIESTE.ID= MESSAGGIATTIVITA.FKIDRICHIESTA
  INNER JOIN PRATICHE RICHIESTE ON RICHIESTE.ID=ATT_RICHIESTE.FKIDPRATICHE
  INNER JOIN ATTIVITA ATT_RISPOSTE ON ATT_RISPOSTE.ID= MESSAGGIATTIVITA.FKIDRISPOSTA
  INNER JOIN PRATICHE RISPOSTE ON RISPOSTE.ID=ATT_RISPOSTE.FKIDPRATICHE
  ORDER BY MESSAGGIATTIVITA.ID;

