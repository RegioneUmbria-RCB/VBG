    @Transient
    public String getRichiedente() {

	StringBuffer answer = new StringBuffer();
	if (StringUtils.isNotBlank(getNominativo())) {
	    answer.append(getNominativo());
	}
	if (StringUtils.isNotBlank(getNome())) {
	    answer.append(" ").append(getNome());
	}
	if (getFormagiuridica() != null && getFormagiuridica().getId().getCodice() != null) {
	    answer.append(" - ").append(getFormagiuridica().getFormagiuridica());
	}
	if (StringUtils.isNotBlank(getCodicefiscale()) && StringUtils.isNotBlank(getPartitaiva())) {
	    answer.append(" (").append(getCodicefiscale()).append(", ").append(getPartitaiva()).append(")");
	} else {
	    if (StringUtils.isNotBlank(getPartitaiva())) {
		answer.append(" (").append(getPartitaiva()).append(")");
	    }
	    if (StringUtils.isNotBlank(getCodicefiscale())) {
		answer.append(" (").append(getCodicefiscale()).append(")");
	    }
	}
	if (StringUtils.isNotBlank(getTipoanagrafe())) {
	    String tecnico = "";
	    if (getTipologia() != null) {
		if (getTipologia().intValue() == -1) {
		    tecnico = " T";
		}
	    }
	    answer.append("- [P").append(getTipoanagrafe()).append(tecnico).append("]");
	}
	setRichiedente(answer.toString());
	return richiedente;
    }

