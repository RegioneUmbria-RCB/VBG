package it.gruppoinit.pal.gp.core.domain.helper;

public class GiorniHelper {

    private String descrizioneGiorno;
    private String numeroIstanza;
    private String occupante;
    private Integer codiceMercatoD;
    private Integer codiceGiorno;

    public String getDescrizioneGiorno() {

	return descrizioneGiorno;
    }

    public void setDescrizioneGiorno(String descrizioneGiorno) {

	this.descrizioneGiorno = descrizioneGiorno;
    }

    public String getNumeroIstanza() {

	return numeroIstanza;
    }

    public void setNumeroIstanza(String numeroIstanza) {

	this.numeroIstanza = numeroIstanza;
    }

    public String getOccupante() {

	return occupante;
    }

    public void setOccupante(String occupante) {

	this.occupante = occupante;
    }

    public Integer getCodiceMercatoD() {

	return codiceMercatoD;
    }

    public void setCodiceMercatoD(Integer codiceMercatoD) {

	this.codiceMercatoD = codiceMercatoD;
    }

    public Integer getCodiceGiorno() {

	return codiceGiorno;
    }

    public void setCodiceGiorno(Integer codiceGiorno) {

	this.codiceGiorno = codiceGiorno;
    }
}
