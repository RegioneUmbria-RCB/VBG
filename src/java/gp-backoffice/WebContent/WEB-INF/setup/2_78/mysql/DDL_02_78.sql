CREATE OR REPLACE ALGORITHM=TEMPTABLE View VW_MERCATIPRESENZETOTALI AS SELECT 'STORICO' AS ORIGINE, MERCATIPRESENZE_STORICO.IDCOMUNE, MERCATIPRESENZE_STORICO.ANNO, MERCATIPRESENZE_STORICO.CODICEANAGRAFE, MERCATIPRESENZE_STORICO.FK_AUTORIZZAZIONI_ID, MERCATIPRESENZE_STORICO.FKCODICEMERCATO, MERCATIPRESENZE_STORICO.FKIDMERCATIUSO, MERCATIPRESENZE_STORICO.FK_IDPOSTEGGIO AS FKIDPOSTEGGIO,  MERCATIPRESENZE_STORICO.NUMEROPRESENZE, TRIM( concat_ws('',ANAGRAFE.NOMINATIVO , ' ' , ANAGRAFE.NOME) ) AS ANAGRAFE, ANAGRAFE.CODICEFISCALE, ANAGRAFE.PARTITAIVA, COMUNI.COMUNE AS COMUNERESIDENZA, CITTADINANZA.CITTADINANZA, STR_TO_DATE(ANAGRAFE.DATAREGDITTE, '%d/%m/%Y' ) AS DATAREGDITTE FROM MERCATIPRESENZE_STORICO inner join ANAGRAFE on ANAGRAFE.IDCOMUNE = MERCATIPRESENZE_STORICO.IDCOMUNE AND ANAGRAFE.CODICEANAGRAFE = MERCATIPRESENZE_STORICO.CODICEANAGRAFE left outer join COMUNI on COMUNI.CODICECOMUNE = ANAGRAFE.COMUNERESIDENZA left outer join CITTADINANZA on CITTADINANZA.CODICE = ANAGRAFE.CODICECITTADINANZA UNION ALL  SELECT 'CALENDARIO' AS ORIGINE, MERCATIPRESENZE_T.IDCOMUNE, MERCATIPRESENZE_T.ANNO, MERCATIPRESENZE_D.CODICEANAGRAFE, MERCATIPRESENZE_D.FK_AUTORIZZAZIONI_ID, MERCATIPRESENZE_T.FKCODICEMERCATO, MERCATIPRESENZE_T.FKIDMERCATIUSO, MERCATIPRESENZE_D.FKIDPOSTEGGIO, MERCATIPRESENZE_D.NUMEROPRESENZE, TRIM( concat_ws('',ANAGRAFE.NOMINATIVO , ' ' , ANAGRAFE.NOME )) AS ANAGRAFE, ANAGRAFE.CODICEFISCALE, ANAGRAFE.PARTITAIVA, COMUNI.COMUNE AS COMUNERESIDENZA, CITTADINANZA.CITTADINANZA, STR_TO_DATE(ANAGRAFE.DATAREGDITTE, '%d/%m/%Y' ) AS DATAREGDITTE FROM MERCATIPRESENZE_T inner join MERCATIPRESENZE_D on MERCATIPRESENZE_D.IDCOMUNE = MERCATIPRESENZE_T.IDCOMUNE AND MERCATIPRESENZE_D.FKIDTESTATA = MERCATIPRESENZE_T.ID inner join ANAGRAFE on ANAGRAFE.IDCOMUNE = MERCATIPRESENZE_D.IDCOMUNE AND ANAGRAFE.CODICEANAGRAFE = MERCATIPRESENZE_D.CODICEANAGRAFE left outer join COMUNI on COMUNI.CODICECOMUNE = ANAGRAFE.COMUNERESIDENZA left outer join CITTADINANZA on CITTADINANZA.CODICE = ANAGRAFE.CODICECITTADINANZA  and mercatipresenze_t.FLAG_CONTEGGIA_PRES_ASS = 1;

