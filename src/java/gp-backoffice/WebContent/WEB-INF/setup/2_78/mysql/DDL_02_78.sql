CREATE OR REPLACE ALGORITHM=MERGE
VIEW VW_ASSENZECONCESSIONARI AS
SELECT COUNT(*) AS numero_assenze, mercati.codicemercato, MERCATI.descrizione AS MERCATO, mercati_uso.id AS codiceuso, mercati_uso.descrizione AS USO, mercati_d.idposteggio, MERCATI_D.codiceposteggio  AS POSTEGGIO, anagrafe.codiceanagrafe, ANAGRAFE.NOMINATIVO, ANAGRAFE.NOME, mercatipresenze_t.anno, mercatipresenze_t.software, mercatipresenze_t.idcomune  FROM  MERCATIPRESENZE_D,  ANAGRAFE,  MERCATI,  MERCATI_USO,  MERCATI_D,  MERCATIPRESENZE_T
  WHERE MERCATIPRESENZE_D.IDCOMUNE = mercatipresenze_t.idcomune AND MERCATIPRESENZE_D.fkidtestata = mercatipresenze_t.id
   AND mercatipresenze_d.idcomune = anagrafe.idcomune AND mercatipresenze_d.codiceconcessionario = anagrafe.codiceanagrafe
   AND MERCATI.IDCOMUNE = mercatipresenze_T.idcomune AND mercati.codicemercato = mercatipresenze_T.fkcodicemercato AND
   MERCATI_USO.IDCOMUNE = MERCATIPRESENZE_T.IDCOMUNE AND MERCATI_USO.id = MERCATIPRESENZE_T.fkidmercatiuso AND mercati_d.idcomune = MERCATIPRESENZE_D.idcomune
   AND mercati_d.idposteggio = mercatipresenze_d.fkidposteggio AND codiceconcessionario  IS NOT  NULL AND ( ( MERCATIPRESENZE_D.CODICEANAGRAFE <> CODICECONCESSIONARIO)
   OR MERCATIPRESENZE_D.CODICEANAGRAFE  IS  NULL ) AND ( flag_assenza_giust  IS  NULL OR flag_assenza_giust = 0)
   AND   mercatipresenze_t.FLAG_CONTEGGIA_PRES_ASS=1
   GROUP BY anagrafe.nominativo, anagrafe.nomE, MERCATI.descrizione, mercati_uso.descrizione, mercati_d.idposteggio, MERCATI_D.codiceposteggio, mercati.codicemercato, mercatipresenze_t.anno, mercatipresenze_t.software, mercatipresenze_t.idcomune, anagrafe.codiceanagrafe, mercati_uso.id ORDER BY mercato,uso, posteggio, nominativo,nome;

