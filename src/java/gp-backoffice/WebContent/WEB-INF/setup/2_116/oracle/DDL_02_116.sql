	FROM (
		SELECT alberoproc_tipisoggetto.idcomune
			,alberoproc_tipisoggetto.FK_CODICETIPOSOGGETTO
			, FO_OBBLIGATORIO
			,ROW_NUMBER() OVER (
				PARTITION BY alberoproc_tipisoggetto.idcomune
				,alberoproc_tipisoggetto.FK_CODICETIPOSOGGETTO ORDER BY alberoproc_tipisoggetto.idcomune ASC
