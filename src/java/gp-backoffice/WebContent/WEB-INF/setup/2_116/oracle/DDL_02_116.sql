			AND alberoproc_tipisoggetto.FK_CODICETIPOSOGGETTO = tipisoggetto.CODICETIPOSOGGETTO
		)
	WHERE rnum = 1
	) t2
	ON (
			t1.idcomune = t2.idcomune
			AND t1.FK_CODICETIPOSOGGETTO = t2.FK_CODICETIPOSOGGETTO
			)
WHEN MATCHED
	THEN
		UPDATE
		SET t1.obbligatorio = coalesce(FO_OBBLIGATORIO,0);


