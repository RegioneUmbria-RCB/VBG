package it.gruppoinit.pal.gp.gestionecalendari.web.command;

public class AnagrafeImpresaFilter {

    private String codicefiscale;
    private String cfPi;
    private String denominazione;
    private String numeroRegImprese;
    private String cognome;
    private String nome;

    public String getCodicefiscale() {

	return codicefiscale;
    }

    public void setCodicefiscale(String codicefiscale) {

	this.codicefiscale = codicefiscale;
    }

    public String getCfPi() {

	return cfPi;
    }

    public void setCfPi(String cfPi) {

	this.cfPi = cfPi;
    }

    public String getDenominazione() {

	return denominazione;
    }

    public void setDenominazione(String denominazione) {

	this.denominazione = denominazione;
    }

    public String getNumeroRegImprese() {

	return numeroRegImprese;
    }

    public void setNumeroRegImprese(String numeroRegImprese) {

	this.numeroRegImprese = numeroRegImprese;
    }

    public String getCognome() {

	return cognome;
    }

    public void setCognome(String cognome) {

	this.cognome = cognome;
    }

    public String getNome() {

	return nome;
    }

    public void setNome(String nome) {

	this.nome = nome;
    }
}
