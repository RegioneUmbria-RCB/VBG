package it.gruppoinit.pal.gp.gestionecalendari.web.command;

public class ManifestazioniAreePubblicheSearchFilter {

    private String comune;
    private String codicecomune;
    private String tipologia;
    private String denominazione;
    private String gioni;
    private String cadenza;

    public String getComune() {

	return comune;
    }

    public void setComune(String comune) {

	this.comune = comune;
    }

    public String getCodicecomune() {

	return codicecomune;
    }

    public void setCodicecomune(String codicecomune) {

	this.codicecomune = codicecomune;
    }

    public String getTipologia() {

	return tipologia;
    }

    public void setTipologia(String tipologia) {

	this.tipologia = tipologia;
    }

    public String getDenominazione() {

	return denominazione;
    }

    public void setDenominazione(String denominazione) {

	this.denominazione = denominazione;
    }

    public String getGioni() {

	return gioni;
    }

    public void setGioni(String gioni) {

	this.gioni = gioni;
    }

    public String getCadenza() {

	return cadenza;
    }

    public void setCadenza(String cadenza) {

	this.cadenza = cadenza;
    }
}
