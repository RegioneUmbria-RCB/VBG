package it.gruppoinit.pal.gp.pay.features.interfaccia;

public class ConnectorConfigHelper {

    private String codice;
    private String descrizione;
    private String javaClass;
    private String cfcodprofilo;
    private String idcomune;

    public String getCodice() {

	return codice;
    }

    public void setCodice(String codice) {

	this.codice = codice;
    }

    public String getDescrizione() {

	return descrizione;
    }

    public void setDescrizione(String descrizione) {

	this.descrizione = descrizione;
    }

    public String getJavaClass() {

	return javaClass;
    }

    public void setJavaClass(String javaClass) {

	this.javaClass = javaClass;
    }

    public String getCfcodprofilo() {

	return cfcodprofilo;
    }

    public void setCfcodprofilo(String cfcodprofilo) {

	this.cfcodprofilo = cfcodprofilo;
    }

    public String getIdcomune() {

	return idcomune;
    }

    public void setIdcomune(String idcomune) {

	this.idcomune = idcomune;
    }
}
