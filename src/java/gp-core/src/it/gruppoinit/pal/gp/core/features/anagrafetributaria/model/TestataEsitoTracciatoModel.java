package it.gruppoinit.pal.gp.core.features.anagrafetributaria.model;

public class TestataEsitoTracciatoModel {

    private Integer id;
    private String descrizione;
    private String tipologia;
    private int numeroGruppi;

    public Integer getId() {

	return id;
    }

    public void setId(Integer id) {

	this.id = id;
    }

    public String getDescrizione() {

	return descrizione;
    }

    public void setDescrizione(String descrizione) {

	this.descrizione = descrizione;
    }

    public String getTipologia() {

	return tipologia;
    }

    public void setTipologia(String tipologia) {

	this.tipologia = tipologia;
    }

    public int getNumeroGruppi() {

	return numeroGruppi;
    }

    public void setNumeroGruppi(int numeroGruppi) {

	this.numeroGruppi = numeroGruppi;
    }
}
