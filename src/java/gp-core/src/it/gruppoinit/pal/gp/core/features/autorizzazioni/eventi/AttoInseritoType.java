package it.gruppoinit.pal.gp.core.features.autorizzazioni.eventi;

public class AttoInseritoType {

    private Integer idAutorizzazione;
    private String classifica;
    private String numeroProposta;
    private Integer annoProposta;

    public Integer getIdAutorizzazione() {

	return idAutorizzazione;
    }

    public void setIdAutorizzazione(Integer idAutorizzazione) {

	this.idAutorizzazione = idAutorizzazione;
    }

    public String getClassifica() {

	return classifica;
    }

    public void setClassifica(String classifica) {

	this.classifica = classifica;
    }

    public String getNumeroProposta() {

	return numeroProposta;
    }

    public void setNumeroProposta(String numeroProposta) {

	this.numeroProposta = numeroProposta;
    }

    public Integer getAnnoProposta() {

	return annoProposta;
    }

    public void setAnnoProposta(Integer annoProposta) {

	this.annoProposta = annoProposta;
    }
}
