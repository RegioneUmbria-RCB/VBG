package it.gruppoinit.pal.gp.core.features.commissioni.upgr;

public class CdsTipologieBean {

    private String idcomune;
    private String software;
    private String tipomovimento;
    private Integer conteggio;
    private Integer codiceamministrazione;

    public String getIdcomune() {

	return idcomune;
    }

    public void setIdcomune(String idcomune) {

	this.idcomune = idcomune;
    }

    public String getTipomovimento() {

	return tipomovimento;
    }

    public void setTipomovimento(String tipomovimento) {

	this.tipomovimento = tipomovimento;
    }

    public Integer getConteggio() {

	return conteggio;
    }

    public void setConteggio(Integer conteggio) {

	this.conteggio = conteggio;
    }

    public Integer getCodiceamministrazione() {

	return codiceamministrazione;
    }

    public void setCodiceamministrazione(Integer codiceamministrazione) {

	this.codiceamministrazione = codiceamministrazione;
    }

    public String getSoftware() {

	return software;
    }

    public void setSoftware(String software) {

	this.software = software;
    }
}
