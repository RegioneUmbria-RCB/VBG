    /**
     * Riporta una descrizione del protocollo del tipo "prot num_prot del dd/MM/yyyy"
     * 
     * @return
     */
    @Transient
    public String getDescProtocollo() {

	StringBuffer protocollo = new StringBuffer();
	if (StringUtils.isNotBlank(getNumeroprotocollo())) {
	    protocollo = protocollo.append("<b>Prot.</b> ").append(getNumeroprotocollo());
	    if (getDataprotocollo() != null) {
		String data = Utilities.formatDate(getDataprotocollo(), false);
		protocollo = protocollo.append(" del ").append(data);
	    }
	}
	return protocollo.toString();
    }

