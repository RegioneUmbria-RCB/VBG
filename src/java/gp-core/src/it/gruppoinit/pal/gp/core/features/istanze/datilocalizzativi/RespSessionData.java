package it.gruppoinit.pal.gp.core.features.istanze.datilocalizzativi;

public class RespSessionData {

    private String status;
    private String messaggio;
    private int fatte;
    private int daFaree;
    private int totali;

    // Getters and Setters
    public String getStatus() {
        return status;
    }

    public void setStatus(String status) {
        this.status = status;
    }

    public String getMessaggio() {
        return messaggio;
    }

    public void setMessaggio(String messaggio) {
        this.messaggio = messaggio;
    }

    public int getFatte() {
        return fatte;
    }

    public void setFatte(int fatte) {
        this.fatte = fatte;
    }

    public int getDaFaree() {
        return daFaree;
    }

    public void setDaFaree(int daFaree) {
        this.daFaree = daFaree;
    }

    public int getTotali() {
        return totali;
    }

    public void setTotali(int totali) {
        this.totali = totali;
    }
	
}
