package it.gruppoinit.pal.gp.core.domain.helper;

public class LayerPDFHelper {

    private String nomelayer;
    private Integer positionX;
    private Integer positionY;
    private String typeFont;
    private Integer dimensionFont;

    public String getNomelayer() {

	return nomelayer;
    }

    public void setNomelayer(String nomelayer) {

	this.nomelayer = nomelayer;
    }

    public Integer getPositionX() {

	return positionX;
    }

    public void setPositionX(Integer positionX) {

	this.positionX = positionX;
    }

    public Integer getPositionY() {

	return positionY;
    }

    public void setPositionY(Integer positionY) {

	this.positionY = positionY;
    }

    public String getTypeFont() {

	return typeFont;
    }

    public void setTypeFont(String typeFont) {

	this.typeFont = typeFont;
    }

    public Integer getDimensionFont() {

	return dimensionFont;
    }

    public void setDimensionFont(Integer dimensionFont) {

	this.dimensionFont = dimensionFont;
    }
}
