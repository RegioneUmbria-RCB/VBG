    @Transient
    public String getTransientLocalizzazionePrimario() {

	String descrizioneLocalizzazione = "";
	if (getIstanzestradarios() != null) {
	    if (getIstanzestradarios().size() > 0) {
		Istanzestradario primario = null;
		for (Istanzestradario istanzestradario : getIstanzestradarios()) {
		    primario = istanzestradario;
		    if (BooleanUtils.isTrue(istanzestradario.getPrimario())) {
			break;
		    }
		}
		if (primario != null) {
		    Stradario stradario = primario.getStradario();
		    if (stradario != null) {
			descrizioneLocalizzazione = StringUtils.defaultIfEmpty(stradario.getPrefisso(), "");
			descrizioneLocalizzazione = descrizioneLocalizzazione.concat(" ")
				.concat(StringUtils.defaultIfEmpty(stradario.getDescrizione(), ""));
		    }
		    if (StringUtils.isNotBlank(primario.getCivico())) {
			descrizioneLocalizzazione = descrizioneLocalizzazione.concat(" ").concat(primario.getCivico());
		    }
		    if (StringUtils.isNotBlank(primario.getEsponente())) {
			descrizioneLocalizzazione = descrizioneLocalizzazione.concat(" ").concat(primario.getEsponente());
		    }
		    if (EntityUtils.getNestedProperty(primario, "stradariocolore.id.codicecolore") != null) {
			descrizioneLocalizzazione = descrizioneLocalizzazione.concat(" ").concat(primario.getStradariocolore().getColore());
		    }
		    if (stradario != null) {
			if (StringUtils.isNotBlank(stradario.getCap())) {
			    descrizioneLocalizzazione = descrizioneLocalizzazione.concat(" - ").concat(stradario.getCap());
			}
			if (StringUtils.isNotBlank(stradario.getLocfraz())) {
			    descrizioneLocalizzazione = descrizioneLocalizzazione.concat(" - ").concat(stradario.getLocfraz());
			}
			if (StringUtils.isNotBlank(stradario.getCodviario())) {
			    descrizioneLocalizzazione = descrizioneLocalizzazione.concat(" (").concat(stradario.getCodviario().concat(")"));
			}
		    }
		}
	    }
	}
	this.transientLocalizzazionePrimario = descrizioneLocalizzazione;
	return this.transientLocalizzazionePrimario;
    }

