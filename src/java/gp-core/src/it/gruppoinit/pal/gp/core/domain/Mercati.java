    public static Mercati FromInserisciMercatoRequest(InserisciMercatoRequest request) {

	if (request == null) {
	    return null;
	}
	Mercati mercato = new Mercati();
	mercato.setAttivo(request.isAttivo());
	mercato.setCodiceEsterno(request.getCodiceEsterno());
	mercato.setComune(new Comuni(request.getCodiceComune()));
	mercato.setDescrizione(request.getDescrizione());
	mercato.setFlagAttivanodoPagam(request.isIntegratoConNodoPagamenti());
	mercato.setFlgTemporaneo(request.isTemporaneo());
	mercato.setManifestazione(new Manifestazioni(request.getTipoManifestazione()));
	mercato.setSoftware(new Software(request.getSoftware()));
	return mercato;
    }

