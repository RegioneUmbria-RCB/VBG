package it.gruppoinit.pal.gp.core.features.istanze.istanzecollegate.upgr;

public class CollegamentiDuplicatiBean {

    private String idComune;
    private int progressivo;
    private int codiceIstanza;
    private Integer codiceIstanzaCollegata;
    private int conteggio;
    private int id;

    public String getIdComune() {

	return idComune;
    }

    public void setIdComune(String idComune) {

	this.idComune = idComune;
    }

    public int getProgressivo() {

	return progressivo;
    }

    public void setProgressivo(int progressivo) {

	this.progressivo = progressivo;
    }

    public int getCodiceIstanza() {

	return codiceIstanza;
    }

    public void setCodiceIstanza(int codiceIstanza) {

	this.codiceIstanza = codiceIstanza;
    }

    public Integer getCodiceIstanzaCollegata() {

	return codiceIstanzaCollegata;
    }

    public void setCodiceIstanzaCollegata(Integer codiceIstanzaCollegata) {

	this.codiceIstanzaCollegata = codiceIstanzaCollegata;
    }

    public int getConteggio() {

	return conteggio;
    }

    public void setConteggio(int conteggio) {

	this.conteggio = conteggio;
    }

    public int getId() {

	return id;
    }

    public void setId(int id) {

	this.id = id;
    }
}
