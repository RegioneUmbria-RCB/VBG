    @Transient
    public static boolean checkConfigurazioneGradSpuntisti(int tipoManifestazione, MercatiConfigurazione mConfigurazione) {

	// mConfigurazione.getFlagAttivaGradSpuntisti() 
	// 0 nessuno
	// 1 Mercati/Fiere
	// 2 mercati
	// 3 fiere
	if (mConfigurazione == null) {
	    return false;
	}
	int conf = mConfigurazione.getFlagAttivaGradSpuntisti() == null ? 0 : mConfigurazione.getFlagAttivaGradSpuntisti();
	if (conf == 0) {
	    return false;
	}
	if (tipoManifestazione == WebConstants.MANIFESTAZIONE_COMPORTAMENTO_FIERA && (conf == 1 || conf == 3)) {
	    // tipoManifestazione	0 - fiere
	    return true;
	}
	return (tipoManifestazione == WebConstants.MANIFESTAZIONE_COMPORTAMENTO_MERCATO && (conf == 1 || conf == 2));
    }

