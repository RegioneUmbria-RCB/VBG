package it.gruppoinit.pal.gp.core.domain.helper;

public class ComuneGraduatorieRestBean {

    private String nome;
    private String nome_provincia;
    private String sigla_provincia;

    public String getNome() {

	return nome;
    }

    public void setNome(String nome) {

	this.nome = nome;
    }

    public String getNome_provincia() {

	return nome_provincia;
    }

    public void setNome_provincia(String nome_provincia) {

	this.nome_provincia = nome_provincia;
    }

    public String getSigla_provincia() {

	return sigla_provincia;
    }

    public void setSigla_provincia(String sigla_provincia) {

	this.sigla_provincia = sigla_provincia;
    }
}
