package it.gruppoinit.pal.gp.core.domain.cart;


public class ModuloRendering {
    
    private String name;
    private String html;
    private String riferimento;
    private String id;
    private String idForJsVariablename;
    private String help;
    /**
     * @return the name
     */
    public String getName() {
    
        return name;
    }
    
    /**
     * @param name the name to set
     */
    public void setName(String name) {
    
        this.name = name;
    }
    
    /**
     * @return the html
     */
    public String getHtml() {
    
        return html;
    }
    
    /**
     * @param html the html to set
     */
    public void setHtml(String html) {
    
        this.html = html;
    }

    
    /**
     * @return the riferimento
     */
    public String getRiferimento() {
    
        return riferimento;
    }

    
    /**
     * @param riferimento the riferimento to set
     */
    public void setRiferimento(String riferimento) {
    
        this.riferimento = riferimento;
    }

    
    /**
     * @return the id
     */
    public String getId() {
    
        return id;
    }

    
    /**
     * @param id the id to set
     */
    public void setId(String id) {
    
        this.id = id;
    }

    
    /**
     * @return the idForJsVariablename
     */
    public String getIdForJsVariablename() {
    
        return idForJsVariablename;
    }

    
    /**
     * @param idForJsVariablename the idForJsVariablename to set
     */
    public void setIdForJsVariablename(String idForJsVariablename) {
    
        this.idForJsVariablename = idForJsVariablename;
    }

    
    /**
     * @return the help
     */
    public String getHelp() {
    
        return help;
    }

    
    /**
     * @param help the help to set
     */
    public void setHelp(String help) {
    
        this.help = help;
    }

}
