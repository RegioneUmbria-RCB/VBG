    @Transient
    public String getTransientListaCodiciPeople() {

	// questo campo transient serve per la jsp list, il controllo isEmpty serve per la ricerca sulla colonna Codice STP
	// per non perdere il valore inserito sul campo di ricerca
	if (inventarioprocedimentipeoples != null && !inventarioprocedimentipeoples.isEmpty()) {
	    StringBuffer sb = new StringBuffer("");
	    for (Inventarioprocedimentipeople inv : inventarioprocedimentipeoples) {
		sb.append(StringUtils.defaultString(inv.getCodProcPeople())).append(" ");
	    }
	    transientListaCodiciPeople = sb.toString();
	}
	return transientListaCodiciPeople;
    }

