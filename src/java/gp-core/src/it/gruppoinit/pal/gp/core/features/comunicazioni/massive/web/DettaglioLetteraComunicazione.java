package it.gruppoinit.pal.gp.core.features.comunicazioni.massive.web;

public class DettaglioLetteraComunicazione {

    private String descrizioneLettera;
    private int codiceOggetto;
    private int codiceLettera;

    public String getDescrizioneLettera() {

	return descrizioneLettera;
    }

    public void setDescrizioneLettera(String descrizioneLettera) {

	this.descrizioneLettera = descrizioneLettera;
    }

    public int getCodiceOggetto() {

	return codiceOggetto;
    }

    public void setCodiceOggetto(int codiceOggetto) {

	this.codiceOggetto = codiceOggetto;
    }

    public int getCodiceLettera() {

	return codiceLettera;
    }

    public void setCodiceLettera(int codiceLettera) {

	this.codiceLettera = codiceLettera;
    }
}
