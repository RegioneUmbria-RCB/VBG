                var sql = @"SELECT 
							  statiistanza.codicestato,
							  statiistanza.stato,
							  statiistanza.modificaistanza
							FROM 
							  istanze left join statiistanza ON 
								istanze.idcomune=statiistanza.idcomune AND 
								istanze.chiusura=statiistanza.codicestato AND 
								istanze.software=statiistanza.software 
							WHERE 
							  istanze.idcomune={0} AND 
							  istanze.codiceistanza={1}";

                sql = this.PreparaQueryParametrica(sql, "idComune", "codiceIstanza");

                using (var cmd = this.db.CreateCommand(sql))
                {
                    cmd.Parameters.Add(this.db.CreateParameter("idComune", cls.IDCOMUNE));
                    cmd.Parameters.Add(this.db.CreateParameter("codiceIstanza", Convert.ToInt32(cls.CODICEISTANZA)));

                    using (var dr = cmd.ExecuteReader())
                    {
                        if (dr.Read())
                        {
                            rVal.CodStatoPratica = dr["codicestato"].ToString();
                            rVal.StatoPratica = dr["stato"].ToString();
                            rVal.ModificaIstanza = Convert.ToInt32(dr["modificaistanza"]);
                        }
                    }

                    if (retStatoIter)
                    {
                        cmd.CommandText = this.PreparaQueryParametrica("SELECT stato FROM istanze_tempistica WHERE idcomune={0} AND codiceistanza={1}", "idComune", "codiceIstanza");

                        using (var dr = cmd.ExecuteReader())
                        {
                            if (dr.Read())
                                rVal.StatoIter = dr["stato"].ToString();
                        }
                    }

                    return rVal;
                }
            }
            finally
            {
                if (closeCnn)
                    this.db.Connection.Close();
            }
        }

