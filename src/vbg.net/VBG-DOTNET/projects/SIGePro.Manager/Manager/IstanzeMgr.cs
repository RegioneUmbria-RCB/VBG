        private Istanze GetById(String codiceIstanza, String idComune, useForeignEnum useForeign)
        {
            var retVal = new Istanze();
            retVal.CODICEISTANZA = codiceIstanza;
            retVal.IDCOMUNE = idComune;
            retVal.UseForeign = useForeign;

            var closeCnn = false;

            if (this.db.Connection.State != ConnectionState.Open)
            {
                this.db.Connection.Open();
                closeCnn = true;
            }

            try
            {
                var mydc = this.db.GetClassList(retVal, true);

                if (mydc.Count == 0)
                {
                    return null;
                }

                var istanza = mydc[0];

                if (String.IsNullOrEmpty(istanza.CODICEPRATICATEL))
                {
                    istanza.CODICEPRATICATEL = this.EstraiCodicePraticaTelematica(this.db, idComune, codiceIstanza);
                }

                return istanza;
            }
            finally
            {
                if (closeCnn)
                {
                    this.db.Connection.Close();
                    closeCnn = false;
                }
            }
        }

