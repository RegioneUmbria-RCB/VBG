using DocumentFormat.OpenXml.Spreadsheet;
using Microsoft.AspNetCore.Components;
using Microsoft.AspNetCore.Components.Forms;
using System.Linq.Expressions;

namespace Vbg.CoreControls.EditFormControls
{
    public abstract class MyBaseFormComponent<TValue> : InputBase<TValue>, IDisposable
    {
        /// <summary>
        /// This Id correspond to the html element id property
        /// Is not mandatory but it should be unique, it's uniqueness is a user responsability
        /// </summary>
        [Parameter]
        public string? Id { get; set; }

        /// <summary>
        /// This property is the html id property of the component container (usually a <div>)
        /// It's value is autogenerated and is unique
        /// </summary>
        protected string? UniqueID { get; private set; }

        /// <summary>
        /// Set to true id the control must contain a value
        /// It will be used in validation process
        /// Default: false
        /// </summary>
        [Parameter]
        public bool Required { get; set; } = false;

        /// <summary>
        /// A regualar expression to be used in control validation process
        /// Default: null
        /// </summary>
        [Parameter]
        public string? RegEx { get; set; }

        /// <summary>
        /// This property is used in control validation process and determine the control appearence
        /// Not validated - Valid - Invalid
        /// Default: null (Not validated)
        /// </summary>
        protected bool? IsValid { get; set; }

        /// <summary>
        /// This parameter is used to load the text of the component label
        /// Default: null
        /// </summary>
        [Parameter]
        public string? ResourceId { get; set; }

        private bool _canEditResourceText;
        /// <summary>
        /// Set whether the text of the component label can be modified
        /// </summary>
        [Parameter]
        public bool CanEditResourceText
        {
            get => !string.IsNullOrEmpty(this.ResourceId) && this._canEditResourceText;
            set => this._canEditResourceText = value;
        }

        /// <summary>
        /// The text of the component label
        /// </summary>
        [Parameter]
        public string? Label { get; set; }

        private bool _showLabel = true;
        /// <summary>
        /// Set whether the component label must be visible or not
        /// Note that if Label propety is null or empty ShowLabel returns false 
        /// </summary>
        [Parameter]
        public virtual bool ShowLabel
        {
            get => !string.IsNullOrEmpty(this.Label) && this._showLabel;
            set => this._showLabel = value;
        }

        /// <summary>
        /// Set whether the control must be enabled or disabled
        /// </summary>
        [Parameter]
        public bool IsDisabled { get; set; }

        /// <summary>
        /// Add custom class to the component container
        /// </summary>
        [Parameter]
        public string CssClassContainer { get; set; } = "";

        /// <summary>
        /// A simple note to display under the control to inform the user
        /// </summary>
        [Parameter]
        public string HelpText { get; set; } = "";

        [Parameter]
        public Expression<Func<TValue>> ValidationFor { get; set; } = default!;

        protected string cssErrorClass { get; private set; } = "";

        private ValidationMessageStore? _parsingValidationMessages;

        protected override void OnInitialized()
        {
            base.OnInitialized();

            this.UniqueID = Convert.ToBase64String(Guid.NewGuid().ToByteArray()).Substring(0, 10).Replace("+", "-").Replace("/", "-");

            if (this.EditContext != null)
            {
                this.EditContext.OnValidationStateChanged += this.OnValidationStateChanged;
                this._parsingValidationMessages = new ValidationMessageStore(this.EditContext);
            }

            if (this.ValueExpression != null)
            {
                var requiredAttribute = this.FieldIdentifier.Model.GetAttributeFrom<System.ComponentModel.DataAnnotations.RequiredAttribute>(this.FieldIdentifier.FieldName);

                if (requiredAttribute != null)
                    this.Required = !requiredAttribute.AllowEmptyStrings;
            }
        }

        private void OnValidationStateChanged(object? sender, ValidationStateChangedEventArgs e)
        {
            this.updateValidation();
        }

        private void updateValidation()
        {
            ClearValidationMessages();

            if (!String.IsNullOrEmpty(this.FieldIdentifier.FieldName) && this.EditContext is not null)
            {
                if (this.EditContext.IsModified(this.FieldIdentifier))
                {
                    this.IsValid = !this.EditContext.GetValidationMessages(this.FieldIdentifier).Any();

                    if (this.Required && string.IsNullOrEmpty(this.CurrentValueAsString))
                    {
                        this.IsValid = false;
                        AddValidationMessage($"Il campo {this.FieldIdentifier.FieldName} è obbligatorio");
                    }

                    if (!string.IsNullOrEmpty(this.RegEx) && System.Text.RegularExpressions.Regex.IsMatch(this.CurrentValueAsString, this.RegEx))
                    {
                        this.IsValid = false;
                        AddValidationMessage($"Il campo {this.FieldIdentifier.FieldName} non rispetta l'espressione regolare {this.RegEx}");
                    }

                    if (!this.PerformCustomValidation(this.FieldIdentifier, this._parsingValidationMessages))
                        this.IsValid = false;

                    //if (this.IsValid.Value && string.IsNullOrEmpty(this.CurrentValueAsString))
                    //    this.IsValid = null;

                    //if (this.IsValid == null)
                    //    this.cssErrorClass = string.Empty;
                    //else
                        this.cssErrorClass = this.IsValid.Value ? "is-valid" : "is-invalid";
                }
                else
                {
                    this.IsValid = null;
                    this.cssErrorClass = string.Empty;
                }
            }
        }

        /// <summary>
        /// Override this method to add a specific validation for the component
        /// use: messageStore.Add(fieldIdentifier, "errorMessageString");
        /// </summary>
        /// <param name="fieldIdentifier">The identifier of the field inside EditContext</param>
        /// <param name="messageStore">The ValidationMessageStore istance containing errors</param>
        /// <returns>true if value is valid, false otherwise (if false remember to add an error message)</returns>
        protected virtual bool PerformCustomValidation(FieldIdentifier fieldIdentifier, ValidationMessageStore messageStore)
        {
            return true;
        }

        public void Dispose()
        {
            if (this.EditContext is not null)
            {
                ClearValidationMessages();
                this.EditContext.OnValidationStateChanged -= this.OnValidationStateChanged;
            }
        }

        public void AddValidationMessage(string Message)
        {
            this._parsingValidationMessages?.Add(this.FieldIdentifier, Message);
        }

        public void ClearValidationMessages()
        {
            this._parsingValidationMessages?.Clear(this.FieldIdentifier);
        }
    }

    public static class ExtensionClass
    {
        public static T GetAttributeFrom<T>(this object instance, string propertyName) where T : Attribute
        {
            var attrType = typeof(T);
            var property = instance.GetType().GetProperty(propertyName);

            if (property == null)
                return null;

            return (T)property.GetCustomAttributes(attrType, false).FirstOrDefault();
        }
    }
}
